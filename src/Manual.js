// シート1枚を、無いか版が古ければ書き直す
function manual_writeSheet_(ss, name, lines) {
  var sheet = ss.getSheetByName(name);
  if (sheet && String(sheet.getRange(1, 1).getValue()) === lines[0]) return;
  if (!sheet) sheet = ss.insertSheet(name);
  sheet.clear();
  var safe = lines.map(function (l) { return [/^[=+\-@]/.test(l) ? "'" + l : l]; });
  sheet.getRange(1, 1, safe.length, 1).setValues(safe);
  try {
    sheet.setColumnWidth(1, 900);
    sheet.getRange(1, 1, safe.length, 1).setWrap(true);
    sheet.getRange(1, 1).setFontWeight('bold');
  } catch (e) {}
}

// 管理画面を開いたときに呼ぶ。失敗しても画面は止めない
function manual_ensureSheets_() {
  try {
    var ss = db_getShiftDb_();
    manual_writeSheet_(ss, 'マニュアル', manual_lines_());
    manual_writeSheet_(ss, '困ったとき（ChatGPT用）', manual_promptLines_());
  } catch (e) {}
}
